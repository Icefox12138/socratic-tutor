CJK = re.compile(r"[\u3400-\u9fff]+")
WORD = re.compile(r"[a-z]{2,}")


def tokens(s):
    """Same tokenisation as samples/generators/make_demo_corpus.py:
    CJK bigrams plus lowercase ASCII words."""
    out = []
    for run in CJK.findall(s):
        if len(run) == 1:
            out.append(run)
        else:
            out.extend(run[i:i + 2] for i in range(len(run) - 1))
    out.extend(WORD.findall(s.lower()))
    return out


def build_pdf(images):
    os.makedirs(PDF_DIR, exist_ok=True)
    path = os.path.join(PDF_DIR, BOOK)
    images[0].save(path, "PDF", save_all=True, append_images=images[1:],
                   resolution=150.0, quality=95)
    return path


def _remove_if_exists(path):
    for candidate in (path, path + "-wal", path + "-shm"):
        if os.path.exists(candidate):
            os.remove(candidate)


def build_db(pages):
    os.makedirs(OUT, exist_ok=True)
    db = os.path.join(OUT, "search.db")
    _remove_if_exists(db)
    con = sqlite3.connect(db)
    try:
        con.execute("PRAGMA journal_mode=WAL")
        con.execute("CREATE TABLE chunks (id INTEGER PRIMARY KEY, source TEXT, "
                    "book TEXT, lang TEXT, page INTEGER, text TEXT, "
                    "visibility TEXT)")
        con.execute("CREATE VIRTUAL TABLE chunks_fts USING fts5("
                    "text, tokenize='unicode61')")
        rows = []
        for page in pages:
            for block in page["blocks"]:
                rows.append((SOURCE, BOOK, page["lang"], page["page"], block,
                             "tutor"))
            for term, expl in page.get("gloss") or []:
                rows.append((SOURCE, BOOK, page["lang"], page["page"],
                             "%s — %s" % (term, expl), "tutor"))
        for i, row in enumerate(rows, 1):
            con.execute("INSERT INTO chunks (id,source,book,lang,page,text,"
                        "visibility) VALUES (?,?,?,?,?,?,?)", (i,) + row)
            con.execute("INSERT INTO chunks_fts (rowid, text) VALUES (?,?)",
                        (i, " ".join(tokens(row[4]))))
        con.execute(
            "CREATE TABLE IF NOT EXISTS toc ("
            "source TEXT, book TEXT, ord INTEGER, level INTEGER, title TEXT,"
            "page_start INTEGER, page_end INTEGER, volume INTEGER, pages INTEGER,"
            "meta TEXT, PRIMARY KEY(source, book, ord))")
        con.execute(
            "INSERT INTO toc(source,book,ord,level,title,page_start,page_end,"
            "volume,pages,meta) VALUES(?,?,?,?,?,?,?,?,?,?)",
            (SOURCE, BOOK, 0, 1,
             "全集（%d 页：Vergil / Homer / 论语 / 老子 / 版权说明）" % len(pages),
             1, len(pages), None, len(pages), "{}"))
        con.commit()
    finally:
        con.close()
    # a closed WAL is checkpointed; drop any leftover side files for a tidy dir
    for suffix in ("-wal", "-shm"):
        p = db + suffix
        if os.path.exists(p):
            try:
                os.remove(p)
            except OSError:
                pass
    lang_chars = {}
    for page in pages:
        text = list(page["blocks"]) + ["%s — %s" % (t, e)
                                       for t, e in page.get("gloss") or []]
        lang_chars[page["lang"]] = lang_chars.get(page["lang"], 0) + sum(
            len(b) for b in text)
    return {"db": db, "chunks": len(rows), "lang_chars": lang_chars}


