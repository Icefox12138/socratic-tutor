def font_dirs():
    out = []
    windir = os.environ.get("WINDIR")      # Windows only; absent elsewhere
    if windir:
        out.append(os.path.join(windir, "Fonts"))
    local = os.environ.get("LOCALAPPDATA")
    if local:
        out.append(os.path.join(local, "Microsoft", "Windows", "Fonts"))
    out.append(os.path.join(HERE, "fonts"))
    out.extend([
        "/usr/share/fonts/truetype/dejavu",
        "/usr/share/fonts/truetype/liberation",
        "/usr/share/fonts/truetype/noto",
        "/usr/share/fonts/opentype/noto",
        "/Library/Fonts",
    ])
    return out


def display_name(filename):
    stem = os.path.splitext(os.path.basename(filename))[0]
    for key in sorted(FONT_DISPLAY, key=len, reverse=True):
        if stem.lower().startswith(key.lower()):
            return FONT_DISPLAY[key]
    return stem


def missing_glyphs(path, index, text):
    """Code points this face cannot draw, or None when fontTools is absent."""
    try:
        from fontTools.ttLib import TTFont
    except ImportError:                                      # pragma: no cover
        return None
    try:
        font = TTFont(path, fontNumber=index)
        try:
            cmap = font.getBestCmap() or {}
        finally:
            font.close()
    except Exception:
        return None
    return "".join(sorted({c for c in text if not c.isspace() and ord(c) not in cmap}))


def page_text_for_font(spec):
    """Every character a page draws with its own font (for coverage checking)."""
    fields = [spec["heading"], spec.get("subheading", ""), spec["license"],
              spec["note"], spec["footer"], spec["hint"]]
    terms = [term for term, _expl in spec.get("gloss") or []]
    return " ".join(fields + list(spec["blocks"]) + terms)


def resolve_fonts():
    """Pick one font per script; skip (with a printed reason) when none covers it."""
    need = {}
    for spec in PAGE_SPECS:
        need.setdefault(spec["font"], "")
        need[spec["font"]] += page_text_for_font(spec)
    # gloss explanations and the "生词 / Glosses" label are set in Chinese on every
    # page that carries a gloss list, so the zh face must cover them too.
    gloss_chars = "生词 / Glosses" + "".join(
        expl for spec in PAGE_SPECS for _term, expl in spec.get("gloss") or [])
    if gloss_chars.strip():
        need["zh"] = need.get("zh", "") + gloss_chars

    dirs = [d for d in font_dirs() if os.path.isdir(d)]
    resolved, skipped = {}, {}
    for key, text in need.items():
        exact, partial = None, None
        for name in FONT_SPECS[key]["candidates"]:
            for directory in dirs:
                path = os.path.join(directory, name)
                if not os.path.isfile(path):
                    continue
                index = 0
                miss = missing_glyphs(path, index, text)
                entry = {"path": path, "index": index, "name": display_name(name),
                         "file": name, "checked": miss is not None,
                         "missing": miss or ""}
                if miss is None:
                    if exact is None:
                        exact = entry          # cannot verify: first hit wins
                    continue
                if not miss:
                    exact = entry
                    break
                if partial is None or len(miss) < len(partial["missing"]):
                    partial = entry
            if exact is not None and exact["checked"] and not exact["missing"]:
                break
        if exact is not None:
            resolved[key] = exact
        else:
            skipped[key] = partial
    return resolved, skipped


def font_for(key, size):
    spec = _RESOLVED[key]
    cache_key = (key, size)
    if cache_key not in _FONT_CACHE:
        _FONT_CACHE[cache_key] = ImageFont.truetype(
            spec["path"], size, index=spec["index"])
    return _FONT_CACHE[cache_key]


# ── drawing helpers ──────────────────────────────────────────────────────────
NO_LINE_START = "，。、；：？！）》」』】…·,.;:?!)]}"


def wrap_words(draw, text, font, width):
    lines, cur = [], ""
    for word in text.split(" "):
        trial = (cur + " " + word).strip()
        if not cur or draw.textlength(trial, font=font) <= width:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def wrap_prose(draw, text, font, width, first_indent=0, rest_indent=0):
    """CJK breaks anywhere; Latin/Greek runs stay whole; punctuation hangs."""
    tokens = re.findall(r"[ \t]+|[\u3400-\u9fff]|[^\s\u3400-\u9fff]+", text)
    lines, cur, first = [], "", True
    limit = width - (first_indent if first else rest_indent)
    for tok in tokens:
        if tok.isspace():
            if cur:
                cur += " "
            continue
        if (not cur or tok in NO_LINE_START
                or draw.textlength(cur + tok, font=font) <= limit):
            cur += tok
        else:
            lines.append((first, cur.rstrip()))
            first = False
            limit = width - rest_indent
            cur = tok
    if cur.strip():
        lines.append((first, cur.rstrip()))
    return lines


def draw_wrapped(draw, text, font, x, y, width, leading, fill=INK,
                 first_indent=0, rest_indent=0):
    for first, line in wrap_prose(draw, text, font, width, first_indent, rest_indent):
        draw.text((x + (first_indent if first else rest_indent), y), line,
                  font=font, fill=fill)
        y += leading
    return y


def render_page(spec, page_no, total, fonts):
    img = Image.new("RGB", (W, H), PAPER)
    d = ImageDraw.Draw(img)
    d.rectangle([MARGIN, MARGIN, W - MARGIN, H - MARGIN], outline=RULE, width=1)

    # running head
    head_font = font_for(spec["font"], 17)
    label = {"latin": "LATIN · VERGIL", "greek": "GREEK · HOMER",
             "zh": "中文 · 公版选文"}.get(spec["lang"], "PUBLIC DOMAIN")
    d.text((76, 62), label, font=head_font, fill=MUTED)
    right = "socratic-tutor · public-demo"
    d.text((W - 76 - d.textlength(right, font=head_font), 62), right,
           font=head_font, fill=MUTED)
    d.line([(76, 102), (W - 76, 102)], fill=RULE, width=1)

    # title block
    heading_size = {"latin": 44, "greek": 40}.get(spec["font"], 44)
    if spec["key"] == "colophon":
        heading_size = 40
    d.text((76, 132), spec["heading"], font=font_for(spec["font"], heading_size),
           fill=INK)
    y = 132 + heading_size + 22
    if spec.get("subheading"):
        d.text((78, y), spec["subheading"], font=font_for(spec["font"], 27),
               fill=ACCENT)
        y += 56
    d.text((78, y), spec["license"], font=font_for(spec["font"], 18), fill=MUTED)
    y += 46
    d.line([(76, y), (W - 76, y)], fill=RULE, width=1)
    y += 34

    # body
    if spec["kind"] == "verse":
        body = font_for(spec["font"], 30)
        num = font_for(spec["font"], 15)
        for i, line in enumerate(spec["blocks"], 1):
            d.text((128, y + 7), "%d" % i, font=num, fill=MUTED, anchor="ra")
            for row in wrap_words(d, line, body, W - 160 - 108):
                d.text((160, y), row, font=body, fill=INK)
                y += 56
            y += 8
    elif spec["kind"] == "prose":
        body = font_for(spec["font"], 34)
        for block in spec["blocks"]:
            y = draw_wrapped(d, block, body, 90, y, W - 180, 60,
                             first_indent=68)
            y += 26
    else:  # bullets
        body = font_for(spec["font"], 25)
        for block in spec["blocks"]:
            d.text((92, y + 2), "·", font=body, fill=ACCENT)
            y = draw_wrapped(d, block, body, 124, y, W - 124 - 92, 42)
            y += 22

    if y > 1120:
        print("  ! page %d body overflows into the hint card (y=%d)" % (page_no, y))

    # glosses: the lesson's vocabulary, visibly present on the page it belongs to
    gloss = spec.get("gloss") or []
    if gloss and fonts.get("zh"):
        y += 24
        d.line([(76, y), (W - 76, y)], fill=RULE, width=1)
        y += 20
        d.text((92, y), "生词 / Glosses", font=font_for("zh", 18), fill=MUTED)
        y += 34
        term_font = font_for(spec["font"], 21)
        expl_font = font_for("zh", 19)
        for term, expl in gloss:
            d.text((100, y), term, font=term_font, fill=INK)
            x = 100 + d.textlength(term, font=term_font) + 14
            d.text((x, y + 1), "— " + expl, font=expl_font, fill=MUTED)
            y += 38
        if y > 1120:
            print("  ! page %d gloss overflows into the hint card (y=%d)"
                  % (page_no, y))

    # try-it card
    card_top, card_bottom = 1140, 1302
    d.rounded_rectangle([90, card_top, W - 90, card_bottom], radius=16,
                        fill=CARD, outline=RULE, width=2)
    zh = fonts.get("zh")
    if zh:
        d.text((120, card_top + 22), "试一试 sidecar 检索：",
               font=font_for("zh", 18), fill=MUTED)
    else:                                                   # pragma: no cover
        d.text((120, card_top + 22), "TRY THE SIDECAR:",
               font=font_for(spec["font"], 18), fill=MUTED)
    d.text((120, card_top + 58), spec["hint"], font=font_for(spec["font"], 25),
           fill=INK)
    d.text((120, card_top + 108),
           "/v1/pages?source=%s&book=%s&page=%d" % (SOURCE, BOOK, page_no),
           font=font_for(spec["font"], 17), fill=MUTED)

    # note + footer
    note = font_for(spec["font"], 18)
    n_y = 1458
    for line in wrap_words(d, spec["note"], note, W - 176) if spec["font"] != "zh" \
            else [ln for _f, ln in wrap_prose(d, spec["note"], note, W - 176)]:
        d.text((88, n_y), line, font=note, fill=MUTED)
        n_y += 28
    d.line([(76, 1584), (W - 76, 1584)], fill=RULE, width=1)
    foot = font_for(spec["font"], 16)
    d.text((76, 1616), spec["footer"], font=foot, fill=MUTED)
    page_label = "%d / %d" % (page_no, total)
    d.text((W - 76 - d.textlength(page_label, font=foot), 1616), page_label,
           font=foot, fill=MUTED)
    return img


